import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({ viewport:{width:1440,height:1000} });
const base = process.env.TEST_URL || 'http://127.0.0.1:8774';
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
try {
  // A missing or disconnected B route must fail before any interaction tests.
  const response=await page.goto(base+'/notes/ingredients/people.html');
  assert.equal(response.status(),200,'Variant B must be served');
  await page.waitForSelector('#sheet .card');
  assert.equal(await page.locator('#sheet .card').count(),18);
  assert.equal(await page.locator('#sheet .card img.portrait:visible').count(),18,'Reuse the existing portraits in B');
  assert.ok(await page.locator('#sheet .card img.portrait').first().evaluate(img=>getComputedStyle(img).visibility!=='hidden'));
  const canvas=page.locator('#sheet canvas').first();
  const firstFrame=await canvas.evaluate(c=>c.toDataURL());
  await page.waitForTimeout(180);
  assert.notEqual(await canvas.evaluate(c=>c.toDataURL()),firstFrame,'The original study must keep moving');
  await page.locator('#motion').click();
  await page.waitForTimeout(80);
  const pausedFrame=await canvas.evaluate(c=>c.toDataURL());
  await page.waitForTimeout(180);
  assert.equal(await canvas.evaluate(c=>c.toDataURL()),pausedFrame,'Pause must hold the actual artwork');
  await page.locator('#sheet .card').nth(7).click();
  await page.waitForSelector('#unmix-panel:visible');
  assert.equal(await page.locator('[data-step="0"]').getAttribute('aria-pressed'),'true');
  await page.locator('[data-step="1"]').click();
  assert.match(await page.locator('#unmix-content').innerText(),/Interpolate gradients across a lattice/);
  await page.locator('#scrub').fill('8.2');
  assert.equal(await page.locator('#scrub-time').innerText(),'8.2 s');
  await page.locator('#scrub-live').click();
  assert.equal(await page.locator('#scrub-time').innerText(),'Live');
  await page.locator('[data-step="2"]').click();
  assert.match(await page.locator('#unmix-title').innerText(),/Ken Perlin/);
  assert.ok(await page.locator('#unmix-content .source-links a').count());
  await page.locator('#unmix-back').click();
  assert.equal(await page.locator('#person-panel').isVisible(),true);
  await page.locator('#show-world').click();
  assert.equal(await page.locator('#network').isVisible(),true);
  assert.equal(await page.locator('.node').count(),18);
  await page.locator('.node').first().focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#unmix-panel').isVisible(),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#detail').isVisible(),false);
  await page.goto(base+'/notes/ingredients/techniques.html');
  await page.waitForSelector('.tile');
  assert.equal(await page.locator('.tile').count(),40);
  await page.getByRole('button',{name:'Signal & interference',exact:true}).click();
  assert.equal(await page.locator('.tile:visible').count(),3);
  await page.locator('.tile:visible').first().click();
  assert.match(await page.locator('#detail-title').innerText(),/Moiré/);
  await page.goto(base+'/notes/ingredients/');
  await page.frameLocator('#a iframe').locator('.card').first().waitFor();
  await page.frameLocator('#b iframe').locator('.tile').first().waitFor();
  assert.equal(await page.frameLocator('#a iframe').locator('.card').count(),18);
  assert.equal(await page.frameLocator('#b iframe').locator('.tile').count(),40);
  await page.getByRole('button',{name:'B · Ingredients',exact:true}).click();
  assert.equal(await page.locator('#a').isVisible(),false);
  assert.equal(await page.locator('#b').isVisible(),true);
  await page.getByRole('button',{name:'A · Minimal',exact:true}).click();
  assert.equal(await page.locator('#a').isVisible(),true);
  assert.equal(await page.locator('#b').isVisible(),false);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:320,height:740});
  for(const route of ['/notes/ingredients/people.html','/notes/ingredients/techniques.html']){
    await page.goto(base+route);
    await page.waitForSelector('.card, .tile');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Phone page must not overflow');
    assert.match(await page.locator('#motion').innerText(),/Play motion/);
  }
  // A stalled optional asset must not leave B opening in A's person-first flow.
  let releaseManifest;
  const heldManifest=new Promise(resolve=>{releaseManifest=resolve});
  await page.route('**/photos/manifest.json',async route=>{await heldManifest;await route.fulfill({json:{}}).catch(()=>{});});
  await page.goto(base+'/notes/ingredients/people.html');
  await page.waitForSelector('.card');
  await page.locator('.card').first().click();
  assert.equal(await page.locator('#unmix-panel').isVisible(),true);
  releaseManifest();
  assert.deepEqual(errors,[]);
  console.log('PASS: B shares all 18 people and 40 techniques; ingredient flow, provenance, connections and filtering work.');
} finally { await browser.close(); }
