import assert from 'node:assert/strict';
import {readFile,stat} from 'node:fs/promises';
const read=path=>readFile(new URL('../'+path,import.meta.url),'utf8');
const html=await read('dist/notes/ingredients/techniques.html');
const start=html.indexOf('<section class="eyebeam-connections" id="about-project"');
const end=html.indexOf('</section>',start);
assert.ok(start>html.indexOf('id="eyebeam-roster"'),'Project creator follows the artist roster');
assert.ok(end<html.indexOf('<footer>'),'About remains in page content before the footer');
const about=html.slice(start,end);
assert.match(about,/ABOUT \/ PROJECT CREATOR/);
assert.match(about,/Yury Gitman · Project creator/);
assert.match(about,/2003 Eyebeam Project Resident/);
assert.match(about,/https:\/\/eyebeam.org\/artists\/yury-gitman\//);
assert.match(about,/\/connections\/\?node=person-yury-gitman#people/);
assert.match(about,/alt="Photograph of Yury Gitman, project creator"/);
assert.ok((await stat(new URL('../dist/notes/ingredients/portrait-sources/yury-gitman-photo.jpg',import.meta.url))).size>1000);
assert.match(html,/src="\/interface\/reading-position.js\?v=compact-1"/,'Preserve reading position integration');
assert.equal((html.match(/Why I’m tracing this/g)||[]).length,1);
const graph=JSON.parse(await read('dist/connections/data.json'));
assert.equal(graph.people.find(p=>p.id==='person-yury-gitman').placement,'Project author');
assert.ok(graph.relationships.some(r=>r.person==='person-yury-gitman'&&r.target==='entity-eyebeam'&&r.source==='https://eyebeam.org/artists/yury-gitman/'),'Retain sourced historical affiliation');
console.log('Project creator About placement, photograph, biography source, reading position and preserved Eyebeam record pass.');
